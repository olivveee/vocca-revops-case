"""Data-quality checks on deals: stage vs dates, amounts, owners, type/source, links to accounts.

Usage: python 1A_sales_dashboard/exploration/checks_deals.py <data_dir>
"""
import sys, pandas as pd
d=sys.argv[1]
D=pd.read_csv(f"{d}/deals.csv",dtype=str); C=pd.read_csv(f"{d}/companies.csv",dtype=str); T=pd.read_csv(f"{d}/sales_team.csv",dtype=str)
def p(k,v): print(f"{k:70s} {v}")
for c in ["created_at","demo_scheduled_date","demo_held_date","quote_sent_date","signed_date","close_date","go_live_date","estimated_closing_date","next_step_due_date"]:
    D[c]=pd.to_datetime(D[c],errors="coerce",utc=True)
for c in ["forecasted_arr","signed_arr","one_off_fees"]: D[c]=pd.to_numeric(D[c],errors="coerce")
EXPORT=pd.Timestamp("2026-09-25",tz="UTC")
closed=D.stage.isin(["Closed Won","Closed Lost"]); won=D.stage=="Closed Won"; lost=D.stage=="Closed Lost"; openm=~closed
print("--- created_at range", D.created_at.min(), D.created_at.max())
print(D.groupby(D.created_at.dt.strftime("%Y-%m")).size().to_string())
print("--- STAGE / DATES")
p("open deals with close_date filled", f"{(openm & D.close_date.notna()).sum()} / {openm.sum()}")
p("won without signed_date", (won & D.signed_date.isna()).sum())
p("won without signed_arr", (won & D.signed_arr.isna()).sum())
p("won with signed_arr==0", (won & (D.signed_arr==0)).sum())
p("won without demo_held_date", (won & D.demo_held_date.isna()).sum())
p("won without quote_sent_date", (won & D.quote_sent_date.isna()).sum())
p("lost with signed_arr", (lost & D.signed_arr.notna()).sum())
p("lost without loss_reason", (lost & D.loss_reason.isna()).sum())
p("non-lost with loss_reason", (~lost & D.loss_reason.notna()).sum())
p("closed_lost_step = Closed won", (D.closed_lost_step=="Closed won").sum())
p("stage>=Demo Held but no demo_held_date", (D.stage.isin(["Demo Held","Qualified","Quoted"]) & D.demo_held_date.isna()).sum())
p("Quoted without quote_sent_date", ((D.stage=="Quoted") & D.quote_sent_date.isna()).sum())
p("close_date in future (> export)", (D.close_date>EXPORT).sum())
p("closed deals with close_date in future", (closed & (D.close_date>EXPORT)).sum())
p("signed_date > close_date +7d (won)", (won & (D.signed_date > D.close_date+pd.Timedelta(days=7))).sum())
p("close_date < created_at -1d", (D.close_date < D.created_at - pd.Timedelta(days=1)).sum())
p("demo_held < created -1d", (D.demo_held_date < D.created_at - pd.Timedelta(days=1)).sum())
p("signed < demo_held", (D.signed_date < D.demo_held_date).sum())
p("go_live < signed", (D.go_live_date < D.signed_date).sum())
p("open deals w/ estimated_closing_date in past", (openm & (D.estimated_closing_date<EXPORT)).sum())
p("open deals w/ next_step overdue", (openm & (D.next_step_due_date<EXPORT)).sum())
p("open deals w/o next_step", (openm & D.next_step_due_date.isna()).sum())
p("open deals created > 90d ago", (openm & (D.created_at<EXPORT-pd.Timedelta(days=90))).sum())
print(D[openm].groupby("stage").apply(lambda g: (EXPORT-g.created_at).dt.days.median()).rename("median_age_days").to_string())
print("--- PROBA vs stage"); print(pd.crosstab(D.stage,D.closing_probability.fillna("NA")).to_string())
print("--- AMOUNTS")
print(D[["forecasted_arr","signed_arr","one_off_fees"]].describe().round(0).to_string())
p("signed_arr negative", (D.signed_arr<0).sum())
p("won signed_arr > 5x forecast", (won & (D.signed_arr>5*D.forecasted_arr)).sum())
p("won signed_arr < forecast/5", (won & (D.signed_arr<D.forecasted_arr/5)).sum())
print("top signed_arr:", D.signed_arr.nlargest(8).tolist())
print(pd.crosstab(D.currency, D.owner.isin(T[T.market=="US"].name)).to_string())
print("--- OWNERS")
own=D.owner.unique(); p("owners not in sales_team", [o for o in own if o not in set(T.name)])
D2=D.merge(T[["name","role","market","status","start_date","end_date"]],left_on="owner",right_on="name",how="left")
print(D2.groupby("role",dropna=False).size().to_string())
D2["end_date"]=pd.to_datetime(D2.end_date,utc=True); D2["start_date"]=pd.to_datetime(D2.start_date,utc=True)
p("deals owned by Left reps (total / still open)", f"{(D2.status=='Left').sum()} / {((D2.status=='Left') & openm.values).sum()}")
p("deals created after owner end_date", (D2.created_at>D2.end_date).sum())
p("deals created before owner start_date -30d", (D2.created_at<D2.start_date-pd.Timedelta(days=30)).sum())
cb=D.created_by.dropna().unique(); p("created_by not in team", [o for o in cb if o not in set(T.name)])
print("--- TYPE / SOURCE"); print(pd.crosstab(D.source.fillna("NA"),D.type).to_string())
p("Group Rollout with group_contract != TRUE", ((D.source=="Group Rollout") & (D.group_contract!="TRUE")).sum())
print("specialty values:", sorted(D.specialty.dropna().unique()))
print("loss reasons:"); print(D.loss_reason.value_counts().to_string())
print("--- ACCOUNTS")
p("company_record_id not in companies", (~D.company_record_id.isin(C.record_id)).sum())
DC=D.merge(C[["record_id","type","lifecycle","country","parent_record_id"]].rename(columns={"record_id":"company_record_id","type":"ctype"}),on="company_record_id",how="left")
print(pd.crosstab(DC.stage,DC.lifecycle.fillna("NA")).to_string())
print(DC.ctype.value_counts(dropna=False).to_string())
p("won deal but company lifecycle not Customer/Churn", (won.values & ~DC.lifecycle.isin(["Customer","Churn"])).sum())
p("companies Customer with no won deal", (C.lifecycle.eq("Customer") & ~C.record_id.isin(D[won].company_record_id)).sum())
dup=D[D.type=="New"].groupby("company_record_id").size(); p("companies with >1 'New' deal", (dup>1).sum())
p("companies with >1 'New' Closed Won", (D[won & (D.type=="New")].groupby("company_record_id").size()>1).sum())
p("duplicate deal_name", D.deal_name.duplicated(keep=False).sum())
p("USD deals on FR company", ((DC.currency=="USD") & (DC.country=="FR")).sum())
p("deal_name with [New]-style prefix", D.deal_name.str.match(r"^\[").sum())
